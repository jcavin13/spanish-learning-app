export function cardImage(id: string) {
  if (!REDRAWN.has(id)) return `/cards/${id}.jpg`;
  const version =
    id === "pie"
      ? 5
      : id === "hombro" || id === "espalda" || id === "tobillo"
        ? 4
        : id === "oreja" || id === "rojo" || id === "rodilla" || id === "pierna"
          ? 3
          : 2;
  return `/cards/${id}.jpg?v=${version}`;
}

export function spanishName(card: Vocab) {
  return card.article ? `${card.article} ${card.es}` : card.es;
}

export function shuffle<T>(items: T[]) {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const swap = copy[i];
    copy[i] = copy[j]!;
    copy[j] = swap!;
  }
  return copy;
}

export type Prompt = { id: string; kind: PromptKind };

export function buildQueue(cards: Vocab[], mode: DirectionMode, round: RoundSize): Prompt[] {
  const prompts: Prompt[] = [];
  for (const card of cards) {
    if (mode === "picture") prompts.push({ id: card.id, kind: "picture" });
    if (mode === "audio") prompts.push({ id: card.id, kind: "audio" });
    if (mode === "es-en" || mode === "both") prompts.push({ id: card.id, kind: "es-en" });
    if (mode === "en-es" || mode === "both") prompts.push({ id: card.id, kind: "en-es" });
  }
  const mixed = shuffle(prompts);
  if (round === "all") return mixed;
  return mixed.slice(0, round);
}

export function foldAnswer(value: string) {
  return value
    .trim()
    .toLocaleLowerCase("es")
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/[¿?¡!.,]/g, "")
    .replace(/\s+/g, " ");
}

export function acceptedAnswers(card: Vocab, expect: "es" | "en") {
  if (expect === "en") {
    const words = [card.en];
    if (card.en === "gray") words.push("grey");
    if (card.en === "gold") words.push("golden");
    if (card.enAlso) {
      for (const extra of card.enAlso.split(",")) {
        const bit = extra.trim();
        if (bit) words.push(bit);
      }
    }
    return words;
  }
  const words = [card.es, spanishName(card)];
  if (card.feminine) words.push(card.feminine);
  if (card.also) words.push(card.also);
  if (card.plural) words.push(card.plural);
  return words;
}

export function isCorrectAnswer(card: Vocab, expect: "es" | "en", typed: string) {
  const got = foldAnswer(typed);
  if (!got) return false;
  return acceptedAnswers(card, expect).some((option) => foldAnswer(option) === got);
}

export function notesFor(card: Vocab) {
  const bits: string[] = [];
  if (card.plural) bits.push(`Plural: ${card.plural}`);
  if (card.feminine) bits.push(`Feminine: ${card.feminine}`);
  else if (card.deck === "color") bits.push("Same with feminine nouns");
  if (card.also) bits.push(`Also: ${card.also}`);
  if (card.deck === "number" && card.enAlso) {
    const digit = card.enAlso.split(",")[0]?.trim();
    if (digit) bits.push(`Numeral: ${digit}`);
  }
  if (card.id === "manana") bits.push("No article. La mañana is the morning.");
  if (card.id === "la-manana") bits.push("With la. Mañana alone is tomorrow.");
  if (card.id === "tarde") bits.push("No article. La tarde is the afternoon.");
  if (card.id === "la-tarde") bits.push("With la. Tarde alone is late. Evening counts too.");
  if (card.id === "ser") bits.push("What something is. Soy, eres, es. Not estar.");
  if (card.id === "estar") bits.push("Where it is, or how it feels. Estoy, estás, está. Not ser.");
  if (card.id === "gustar") bits.push("Me gusta. The thing does the pleasing.");
  if (card.id === "poder") bits.push("Puedo means I can.");
  return bits;
}
